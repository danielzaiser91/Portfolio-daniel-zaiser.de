/**
 * Writes a content hash per preview image into src/app/data/preview-versions.ts.
 * The hash goes into the image URL, so a replaced image gets a new address:
 * previews load lazily and are cached for 4 h, which even Ctrl+Shift+R does not reach.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '../public/images/previews/projects');
const out = path.join(__dirname, '../src/app/data/preview-versions.ts');

const versions = Object.fromEntries(
  fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.webp'))
    .sort()
    .map((f) => [
      f.slice(0, -'.webp'.length),
      crypto.createHash('sha1').update(fs.readFileSync(path.join(dir, f))).digest('hex').slice(0, 8),
    ]),
);

fs.writeFileSync(
  out,
  '// Generated by tools/preview-versions.js (runs before every build) — do not edit.\n' +
    `export const PREVIEW_VERSIONS: Record<string, string> = ${JSON.stringify(versions, null, 2)};\n`,
);
console.log(`preview-versions: ${Object.keys(versions).length} images`);
